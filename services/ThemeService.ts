/**
 * Generate CSS Custom Properties (CSS variables) object for a given ThemeMeta
 */
export function getThemeCssVariables(theme: ThemeMeta): React.CSSProperties {
  const c = theme.colors;
  const e = theme.effects;
  const typ = theme.typography;

  return {
    ["--theme-page-bg" as any]: c.pageBackground,
    ["--theme-profile-bg" as any]: c.profileBackground,
    ["--theme-card-bg" as any]: c.cardBackground,
    ["--theme-elevated-bg" as any]: c.elevatedBackground,
    ["--theme-primary-text" as any]: c.primaryText,
    ["--theme-secondary-text" as any]: c.secondaryText,
    ["--theme-muted-text" as any]: c.mutedText,
    ["--theme-accent" as any]: c.accent,
    ["--theme-accent-text" as any]: c.accentText,
    ["--theme-accent-soft" as any]: c.accentSoft,
    ["--theme-accent-border" as any]: c.accentBorder,
    ["--theme-border" as any]: c.border,
    ["--theme-divider" as any]: c.divider,
    ["--theme-radius" as any]: e.radius || "24px",
    ["--theme-shadow" as any]: e.shadow || "none",
    ["--theme-card-shadow" as any]: e.cardShadow || "none",
    ["--theme-font-family" as any]: typ.fontFamily || "inherit",
    ["--theme-heading-font" as any]: typ.headingFontFamily || "inherit",
    ["--theme-heading-weight" as any]: typ.headingWeight || "700",
    ["--theme-letter-spacing" as any]: typ.letterSpacing || "normal",
  };
}

export const ThemeService = {
  getSelectedTheme(): ThemeKey {
    return themeRepository.get();
  },

  setSelectedTheme(themeKey: ThemeKey, isDashboardChange = false): void {
    themeRepository.save(themeKey);
    const email = authRepository.getPendingEmail();
    if (email) {
      fetch("/api/creator/profile", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          email,
          themeKey,
          incrementThemeCount: isDashboardChange,
        }),
      })
        .then((r) => r.json())
        .then((data) => {
          if (data.success && typeof data.profile?.themeChangesCount === "number") {
            this.syncThemeChangesCount(data.profile.themeChangesCount);
          }
        })
        .catch((e) => console.error("Failed to save themeKey to MySQL DB:", e));
    }
  },

  syncThemeChangesCount(count: number): void {
    if (typeof window !== "undefined") {
      localStorage.setItem("inflixo_theme_changes_count", count.toString());
    }
  },

  getThemeChangesCount(): number {
    if (typeof window === "undefined") return 0;
    const val = localStorage.getItem("inflixo_theme_changes_count");
    return val ? parseInt(val, 10) || 0 : 0;
  },

  incrementThemeChangesCount(): number {
    if (typeof window === "undefined") return 0;
    const current = this.getThemeChangesCount();
    const updated = current + 1;
    localStorage.setItem("inflixo_theme_changes_count", updated.toString());
    return updated;
  },

  checkThemeChangeLimit(): { allowed: boolean; isPro: boolean; remaining: number; count: number } {
    return { allowed: true, isPro: true, remaining: Infinity, count: 0 };
  },

  getThemeMeta(themeKey?: string): ThemeMeta {
    return THEME_LIST.find((t) => t.key === themeKey) ?? THEME_LIST[1];
  },

  list(): ThemeMeta[] {
    return THEME_LIST;
  },
};
